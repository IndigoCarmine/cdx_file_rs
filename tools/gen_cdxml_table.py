"""Generate src/cdxml/table.rs from the CDX/CDXML documentation in doc/md.

Each property page names its CDXML attribute, its CDX tag and its data type, and enumerated
properties list their CDXML value names. Each object page names its CDXML element and tag.

    python tools/gen_cdxml_table.py > src/cdxml/table.rs
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..", "doc", "md")


def field(text, name):
    m = re.search(r"^\|\s*" + re.escape(name) + r"\s*\|\s*(.*?)\s*\|", text, re.M)
    return m.group(1).strip() if m else None


def data_type(raw):
    m = re.match(r"\[?([A-Za-z0-9]+)", raw or "")
    return m.group(1) if m else None


def enum_values(text):
    vals = []
    for m in re.finditer(r"^\|\s*(-?\d+|0x[0-9A-Fa-f]+)\s*\|\s*([A-Za-z][A-Za-z0-9_]*)\s*\|", text, re.M):
        vals.append((int(m.group(1), 0), m.group(2)))
    return vals


def props():
    out = {}
    d = os.path.join(ROOT, "properties")
    for f in sorted(os.listdir(d)):
        text = open(os.path.join(d, f), encoding="utf-8").read()
        name, tag = field(text, "CDXML Name:"), field(text, "CDX Constant Value:")
        if not name or not tag or not re.match(r"0x[0-9A-Fa-f]+$", tag):
            continue
        out.setdefault(name, (int(tag, 16), data_type(field(text, "Data Size:")), enum_values(text)))
    return out


def objects():
    out = {}
    for f in sorted(os.listdir(ROOT)):
        if not f.endswith(".md"):
            continue
        text = open(os.path.join(ROOT, f), encoding="utf-8").read()
        name, tag = field(text, "CDXML Name:"), field(text, "CDX Constant Value:")
        if name and tag and re.match(r"0x8[0-9A-Fa-f]{3}$", tag):
            out.setdefault(name, int(tag, 16))
    return out


# Properties whose documentation pages are missing (archived as redirects), from ChemDraw's
# CDXConstants.h. `SupersededBy` is confirmed by sample_cdx/Reaction.cdx (a graphic arrow
# superseded by an arrow object).
SUPPLEMENT = {
    "SupersededBy": (0x0013, "CDXObjectID", []),
    "Center3D": (0x0209, "CDXPoint3D", []),
    "MajorAxisEnd3D": (0x020A, "CDXPoint3D", []),
    "MinorAxisEnd3D": (0x020B, "CDXPoint3D", []),
    "ArrowheadType": (0x0A2F, "INT16", [(1, "Solid"), (2, "Hollow"), (3, "Angle")]),
    "ArrowheadCenterSize": (0x0A30, "INT16", []),
    "ArrowheadWidth": (0x0A31, "INT16", []),
    "ShadowSize": (0x0A32, "INT16", []),
    "ArrowShaftSpacing": (0x0A33, "INT16", []),
    "EquilibriumRatio": (0x0A34, "FLOAT64", []),
    "ArrowheadHead": (0x0A35, "INT16", [(0, "Unspecified"), (1, "None"), (2, "Full"), (3, "HalfLeft"), (4, "HalfRight")]),
    "ArrowheadTail": (0x0A36, "INT16", [(0, "Unspecified"), (1, "None"), (2, "Full"), (3, "HalfLeft"), (4, "HalfRight")]),
    "FillType": (0x0A37, "INT16", [(0, "Unspecified"), (1, "None"), (2, "Solid"), (3, "Shaded"), (4, "Gradient"), (5, "Pattern")]),
    "CurveSpacing": (0x0A38, "INT16", []),
    "Closed": (0x0A39, "CDXBoolean", []),
    "Dipole": (0x0A3A, "CDXBoolean", []),
    "NoGo": (0x0A3B, "INT8", [(0, "Unspecified"), (1, "None"), (2, "Cross"), (3, "Hash")]),
    "CornerRadius": (0x0A3C, "INT16", []),
    "FrameType": (0x0A3D, "INT16", []),
}
# Object tags from ChemDraw's CDXConstants.h, which the doc pages get wrong or leave out.
SUPPLEMENT_OBJECTS = {"border": 0x801A, "geometry": 0x801B, "constraint": 0x801C, "tlcplate": 0x801D,
                      "tlclane": 0x801E, "tlcspot": 0x801F, "chemicalproperty": 0x8020, "arrow": 0x8021,
                      "stoichiometrygrid": 0x8022, "sgcomponent": 0x8023, "sgdatum": 0x8024,
                      "annotation": 0x802B}

# CDX data type -> the Rust `Kind` variant that encodes it.
KINDS = {
    "INT8": "I8", "UINT8": "U8", "INT16": "I16", "UINT16": "U16", "INT32": "I32", "UINT32": "U32",
    "FLOAT64": "F64", "CDXBoolean": "Bool", "CDXBooleanImplied": "BoolImplied",
    "CDXCoordinate": "Coordinate", "CDXPoint2D": "Point2D", "CDXPoint3D": "Point3D",
    "CDXRectangle": "Rectangle", "CDXObjectID": "ObjectId", "CDXObjectIDArray": "ObjectIdArray",
    "CDXObjectIDArrayWithCounts": "ObjectIdArrayWithCounts", "CDXString": "String",
    "CDXCurvePoints": "CurvePoints", "CDXCurvePoints3D": "CurvePoints3D",
}


def emit(p, o):
    p = dict(p)
    for k, v in SUPPLEMENT.items():
        p.setdefault(k, v)
    o = {n: t for n, t in o.items() if t not in SUPPLEMENT_OBJECTS.values()}
    o.update(SUPPLEMENT_OBJECTS)
    o["objecttag"] = 0x8011
    print("// @generated by tools/gen_cdxml_table.py from doc/md -- do not edit by hand.")
    print("use super::Kind;")
    print()
    print("/// CDXML element name and CDX object tag.")
    print("pub(super) const OBJECTS: &[(&str, u16)] = &[")
    for n, t in sorted(o.items(), key=lambda x: x[1]):
        print(f'    ("{n}", 0x{t:04X}),')
    print("];")
    print()
    print("/// CDXML attribute name, CDX property tag, value encoding and enumerated value names.")
    print("pub(super) const PROPERTIES: &[(&str, u16, Kind, &[(i32, &str)])] = &[")
    for n, (t, ty, e) in sorted(p.items(), key=lambda x: x[1][0]):
        kind = KINDS.get(ty)
        if kind is None or n in ("fonttable", "colortable"):
            continue
        en = ", ".join(f'({v}, "{nm}")' for v, nm in e)
        print(f'    ("{n}", 0x{t:04X}, Kind::{kind}, &[{en}]),')
    print("];")


if __name__ == "__main__":
    p, o = props(), objects()
    if "--check" in sys.argv:
        for n, (t, ty, e) in sorted(p.items(), key=lambda x: x[1][0]):
            print(hex(t), n, ty, len(e))
        print(o)
        sys.exit()
    emit(p, o)
